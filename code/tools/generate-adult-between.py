"""Generate adult entry configurations from the approved shared study sources."""
from pathlib import Path
import hashlib
import json
import re

ROOT = Path(__file__).resolve().parents[2]
ADULT = ROOT / 'code/experiments/experiment1/adults'


def generate():
    scenarios = json.loads((ROOT / 'docs/scenarios.json').read_text())['scenarios']
    texts = json.loads((ROOT / 'docs/narration/source.json').read_text())
    timing = json.loads((ROOT / 'docs/narration/demo-timing.json').read_text())
    conditions = {}
    for experiment, condition in [(1, 'victim_not_careless'), (2, 'victim_careless')]:
        images = ROOT / f'code/experiments/experiment{experiment}/adults/images'
        conditions[condition] = {
            'experiment': experiment, 'audience': 'adults',
            'assetRoot': '../' if experiment == 1 else '../../../experiment2/adults/',
            'scenarios': [{k: v for k, v in s.items() if k not in
                           ['deck', 'deck_sha256', 'experiment', 'caption_format']}
                          for s in scenarios if s['experiment'] == experiment],
            'texts': texts, 'clips': {}, 'demoTiming': timing,
            'assetDigests': {str(p.relative_to(images)): hashlib.sha256(p.read_bytes()).hexdigest()
                            for p in sorted(images.rglob('*')) if p.is_file()},
        }
    target = ADULT / 'between-subjects'
    target.mkdir(exist_ok=True)
    (target / 'configuration.js').write_text(
        '// Generated by code/tools/generate-adult-between.py.\n'
        'globalThis.TORT_ADULT_CONDITIONS = ' + json.dumps(conditions, ensure_ascii=False, indent=2) + ';\n')
    # New named single-condition entries retain the existing scripts and assets.
    single = ADULT / 'single-condition'
    single.mkdir(exist_ok=True)
    for name in ['index.html', 'pilot-preview.html']:
        html = (ADULT / name).read_text().replace('../../../shared/', '../../../../shared/')
        html = html.replace('src="js/experiment.js', 'src="../js/experiment.js')
        if name == 'index.html':
            html = html.replace('<div id="jspsych-target">',
                                '<script>globalThis.TORT_LOCAL_OPTIONS={assetRoot:"../"};</script><div id="jspsych-target">')
        else:
            html = html.replace('globalThis.TORT_LOCAL_OPTIONS={review:true,',
                                'globalThis.TORT_LOCAL_OPTIONS={assetRoot:"../",review:true,')
        (single / name).write_text(html)
    for name in ['index.html', 'pilot-preview.html']:
        page = target / name
        html = page.read_text()
        def version(match):
            src = match[1].split('?', 1)[0]
            digest = hashlib.sha256((page.parent / src).read_bytes()).hexdigest()[:12]
            return f'<script src="{src}?v={digest}"></script>'
        html = re.sub(r'<script src="([^"]*(?:pilot-runtime|pilot-adult-forms|configuration|study)\.js)(?:\?[^"]*)?"></script>', version, html)
        page.write_text(html)


if __name__ == '__main__':
    generate()
